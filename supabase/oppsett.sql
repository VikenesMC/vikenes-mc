-- Postane i dagens rute, i rekkjefølgje
create or replace function public._route_stops(p_event bigint)
returns table (pos int, stop_id bigint, name text, address text, code text)
language sql stable security definer set search_path = public as $$
  select rs.position, s.id, s.name, s.address, s.code
  from public.events e
  join public.route_stops rs on rs.route_id = e.active_route_id
  join public.stops s on s.id = rs.stop_id
  where e.id = p_event
  order by rs.position
$$;

-- Neste post for ei gruppe (eller mål)
create or replace function public._next_for_group(p_group bigint)
returns json language plpgsql stable security definer set search_path = public as $$
declare
  g public.groups;
  e public.events;
  r record;
begin
  select * into g from public.groups where id = p_group;
  select * into e from public.events where id = g.event_id;
  select * into r from public._route_stops(g.event_id) rs
   where not exists (select 1 from public.group_stops gs where gs.group_id = g.id and gs.stop_id = rs.stop_id)
   order by rs.pos limit 1;
  if found then
    return json_build_object('kind', 'stop', 'name', r.name, 'address', r.address);
  end if;
  return json_build_object('kind', 'finish', 'name', e.finish_name, 'address', e.finish_address);
end $$;

create or replace function public._group_points(p_group bigint)
returns int language sql stable security definer set search_path = public as $$
  select coalesce(sum(points), 0)::int from public.group_answers where group_id = p_group
$$;

